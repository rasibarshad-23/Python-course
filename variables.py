#variables in Pyton (string, integer, float, boolean)

#string
first_name = "Rasib"
last_name = "Arshad"

print(f"My  first name is: {first_name}")
print(f"My last name is: {last_name}")

#integers
age = 20

print(f"My age is: {age}")

#float
cgpa = 3.61
temperature = 41.4

print(f"My CGPA is: {cgpa}")
print(f"The temperature is: {temperature}")

#boolean
is_student = True

if is_student:
    print("I am a student")
else:
    print("I am not a student")